    const interpolate = (value, params = {}) => String(value ?? '').replace(/\{(\w+)\}/g, (_match, key) => (
        params[key] === undefined || params[key] === null ? '' : String(params[key])
    ));

    const normalizeLanguageTag = (value) => {
        if (typeof value !== 'string') {
            return '';
        }

        const [rawLanguage = '', rawRegion = ''] = value.replace('-', '_').split('_');
        const language = rawLanguage.toLowerCase();
        const region = rawRegion.toUpperCase();

        return region ? `${language}_${region}` : language;
    };

    const resolveStartupLanguage = ({
        storage = globalScope.localStorage,
        navigatorObject = globalScope.navigator,
        intlObject = globalScope.Intl
    } = {}) => {
        const supportedLanguages = new Set(Object.keys(translations));
        let storedLanguage = '';

        try {
            storedLanguage = normalizeLanguageTag(storage?.getItem?.('wprint3d.language'));
        } catch (_error) {}

        if (storedLanguage && storedLanguage !== 'auto' && supportedLanguages.has(storedLanguage)) {
            return storedLanguage;
        }

        let resolvedOptions = {};

        try {
            resolvedOptions = intlObject?.DateTimeFormat?.().resolvedOptions?.() ?? {};
        } catch (_error) {}

        const languageTags = [
            ...(Array.isArray(navigatorObject?.languages) ? navigatorObject.languages : []),
            navigatorObject?.language,
            resolvedOptions.locale
        ].map(normalizeLanguageTag).filter(Boolean);
        const isArgentinaTimeZone = resolvedOptions.timeZone?.startsWith('America/Argentina/')
            || ARGENTINA_TIME_ZONES.has(resolvedOptions.timeZone);

        if (isArgentinaTimeZone && languageTags.some((language) => language.startsWith('es'))) {
            return 'es_AR';
        }

        for (const language of languageTags) {
            if (supportedLanguages.has(language)) {
                return language;
            }
        }

        for (const language of languageTags) {
            const [baseLanguage] = language.split('_');

            if (supportedLanguages.has(baseLanguage)) {
                return baseLanguage;
            }
        }

        return 'en';
    };

    const createStartupTranslator = (language = 'en') => {
        const selectedTranslations = translations[language] ?? translations.en;

        return (key, params = {}) => interpolate(
            selectedTranslations[key] ?? translations.en[key] ?? key,
            params
        );
    };

    const startupLocalizationUtils = {
        createStartupTranslator,
        interpolate,
        normalizeLanguageTag,
        resolveStartupLanguage,
        translations
    };

    if (typeof module !== 'undefined' && module.exports) {
        module.exports = startupLocalizationUtils;
    }

    globalScope.startupLocalizationUtils = startupLocalizationUtils;
